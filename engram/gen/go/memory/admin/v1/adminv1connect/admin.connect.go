// Control-plane API served on the same port as memory.v1 behind the admin interceptor. Scopes and routes (decisions
// D13, N139, N157, N167, reviews A-4, A-6, A-12): `engram.operator` is fleet-wide with its own audience and covers
// ShardService, MoveService, ListTenants, CreateTenant, UpdateTenantLimits, and GetTenant, DeleteTenant and
// GetTenantOperation on the admin route (an operator token carries no tenant, so the tenant-bound check is skipped for
// it on that route only); those methods are served ONLY on the separate Envoy admin route that is not exposed to
// tenants. `tenant.admin` is tenant-bound (the interceptor enforces token.tenant_id == request.tenant_id) and covers
// the tenant's own lifecycle: GetTenant, DeleteTenant, GetTenantOperation and UpdateTenant (display_name, config),
// served on the tenant-facing listener. A tenant administrator can therefore never raise its own quotas or change its
// isolation. `engram.worker` is the workers' service identity, valid on exactly ReleaseNamespace and CleanupMove and
// bound to the worker's cell by a `cell` claim checked against the shard's cell; it carries no other operator right.
// Every method has exactly one scope, so the interceptor's per-method policy table is the only enforcement point. Three
// services fixed by decision D1:
//   TenantService — tenants, quotas, config, isolation;
//   ShardService  — shard registry and namespace → shard resolution;
//   MoveService   — the per-namespace move protocol of decision D5: freeze,
//                   then copy every table from the static source, verify by equality, build the indexes under the
//                   freeze, cut over with a `ready` state and a catalog CAS as the point of no
