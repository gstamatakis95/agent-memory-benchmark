// MoveServiceClient is a client for the memory.admin.v1.MoveService service.
type MoveServiceClient interface {
	// StartMove plans a move and starts the move executor in engram-worker. Plan computes the window estimate W_est from
	// the namespace's stats. The rebalancer starts a move unattended only at W_est <= 10 min (about 350 k facts); above
	// that the caller must pass an explicit `window` (PreconditionFailed MOVE_WINDOW_REQUIRED otherwise), and the call is
	// refused (MOVE_WINDOW_TOO_SHORT) unless window >= max(1.5 W_est, W_est + 10 min); the window is capped at 8 h, the
	// default is 4 h (decision N173). `estimate_only` returns the estimate without planning. One move per namespace at a
	// time (ABORTED + OperationConflict). The target must have a completed backup and a healthy WAL archiver, else
	// PreconditionFailed{MOVE_TARGET_ARCHIVE_UNHEALTHY} (decision N179), and must run an HA profile (a standby that
	// replays the seal); a `single`-profile target is refused with PreconditionFailed{MOVE_TARGET_NOT_HA} (decision
	// N190). `meta.request_id` is required. Scope engram.operator.
	StartMove(context.Context, *connect.Request[v1.StartMoveRequest]) (*connect.Response[v1.StartMoveResponse], error)
	// GetMove returns the move with progress.
	GetMove(context.Context, *connect.Request[v1.GetMoveRequest]) (*connect.Response[v1.GetMoveResponse], error)
	// ListMoves lists moves, newest first.
	ListMoves(context.Context, *connect.Request[v1.ListMovesRequest]) (*connect.Response[v1.ListMovesResponse], error)
	// RollbackMove aborts a move that has not passed its point of no return
	// (the catalog CAS (a″) `cutover → committed`, decision N125): before
	// Freeze the source is `abort_move`d; after Freeze the rollback wins the `rolled_back` CAS, waits until the standby
	// replayed it (decision N171), thaws the source (also while the target is
	// unreachable: a `ready` target accepts nothing and is un-readied at its next contact) and the target goes back to
	// `incoming`; then the target's copied rows, indexes and ownership row are deleted. Onto a shard that had a
	// `moved_out` row the permanent fence value is restored. The executor takes the same path by itself at the freeze
	// deadline (MoveWindowExceeded, decision N160). After (a″) it fails PreconditionFailed{MOVE_PAST_COMMIT} (a rollback
	// is a new move back); no MoveFenced reaches the wire. `meta.request_id` is required (INVALID_ARGUMENT otherwise).
	RollbackMove(context.Context, *connect.Request[v1.RollbackMoveRequest]) (*connect.Response[v1.RollbackMoveResponse], error)
	// CleanupMove takes `committed -> cleaning` under the 24 h gate (decision N170: `now() >= Move.activated_at + 24 h`;
	// FAILED_PRECONDITION before that) and nothing else; the cleanup activity records `done` after one further zero-row
	// `engram_cleanup_namespace` (decision N184). A call on a `cleaning` or `done` move returns it. `meta.request_id` is
	// required. The physical work is
	// driven by the cleanup activity, which holds both shard handles: it drops the namespace's partial indexes on the
	// source shard by their deterministic names and deletes its rows (`engram_cleanup_namespace`, batched, only while the
	// row reads `cleaning`). The source blob prefix is kept until `finished_at + 28 d` (decision N123). The `moved_out`
	// ownership row stays forever. Scope engram.worker (cell-bound, decision N167) or engram.operator. Idempotent.
	CleanupMove(context.Context, *connect.Request[v1.CleanupMoveRequest]) (*connect.Response[v1.CleanupMoveResponse], error)
}

