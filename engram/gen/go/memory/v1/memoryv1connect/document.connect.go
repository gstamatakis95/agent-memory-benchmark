// DocumentService: read and delete documents (the client-addressed unit of retain and delete). Documents are created
// only through MemoryService.Retain; this service never writes content. The one mutation it offers, UpdateDocumentTags,
// changes the filter tags of a document row.
//
// DeleteDocument is UNARY and returns an Operation because the delete has two halves (decisions D8, N115, N119). The
// synchronous half is an O(1) soft-delete marker: one shard transaction, under the document lock, flips the document to
// DELETING and clears its summary, context, metadata and tags, inserts a document tombstone and a deletion-log row and
// writes the outbox event; after it COMMITS the delete intent object is written to blob storage (N122) and only then
// does the call return. From that ack on, every read path (Recall, Reflect, GetMemory, ListMemories, GetPage,
// SearchPages, StreamSnapshot, and this service) hides everything derived from the document, evaluated at read time
// against the tombstone set (N116, N117); nothing is walked or stamped at delete time. The asynchronous half is the
// throttled per-namespace Expunge workflow (N119) that the returned Operation tracks: materialize (<= 15 min), purge
// rows and blobs (<= 24 h), derived versions reduced to content-free stubs, index rebuild (<= 48 h). Recall SLOs may
// degrade for the namespace while the tombstone is pending. A client that needs "no longer returned" needs nothing
// beyond the ack; one that needs "storage reclaimed" waits on the Operation.
//
// Tombstone view (decision N136). A document in state DELETING is returned by GetDocument and
// ListDocuments(include_deleting) as its tombstone only: document_id, state, deleted_at, up_to_version and
// delete_operation_id; every content-derived field (summary, context, metadata, tags, content hash, counts, versions)
// is empty. GetDocumentVersion and GetDocumentBody of a version the tombstone covers answer NOT_FOUND with reason
// DOCUMENT_DELETED. A Retain into the same document_id starts a new life above up_to_version and is served normally.
// The same cover rule filters every DocumentService path: a revived document lists only the versions above the pending
// tombstone's up_to_version (GetDocument with include_versions, ListDocuments), and a tombstone never matches a
// non-empty tag_filter or metadata filter (its tags and metadata are empty by construction; decision N157, review
// A-14). DocumentState is generated from the same table as the SQL document_state enum: SQL `deleted` is never exposed,
// and INGESTING is SQL `active` with current_version = 0.

