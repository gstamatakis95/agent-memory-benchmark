// ExportService (phase 3): per-namespace snapshots to blob storage under the namespace's shard prefix
// (`{shard}/{tenant}/{ns}/export/v{n}/…`, decision D12), served back to thin clients that sync them next to an agent
// for grep-style local search.
//
// Versions are dense integers per namespace. Snapshot v{n} always contains a full set of files and, for n > 1, ALWAYS
// contains `delta-v{n-1}-v{n}.jsonl.zst`, computed by diffing the two snapshots by (id, version) with delete records,
// and lists `deleted_ids` in its manifest, even when v{n-1} has expired or been garbage-collected (decision N126). A
// client at v{n-1} downloads only the delta and applies the deletes before serving anything; a client further behind
// applies consecutive deltas or falls back to the full files. A local copy whose version is `expired` is refused by the
// sync client until it has applied the next delta (the delta carries the delete records).
//
// Curation (decision N126). The files are built through the read-time visibility predicate at write time and are static
// afterwards (a compressed byte stream cannot be filtered on read). A delete therefore EXPIRES the snapshots that could
// contain the document; Invalidate and Restore never expire a snapshot. Instead GetSnapshotManifest returns a live
// `hidden_overlay` (the currently invalidated facts and the derived versions the read predicate hides now) that the
// sync client applies before serving, so curation reaches a synced agent within one manifest poll and the next snapshot
// honours it. The overlay is computed from the live predicate (the evidence-segment test over `fact_hidden(invalidate)`
// and the open tombstones), not from `derived_hidden` alone, so it is correct before Materialize has run, and it is
// restricted to markers newer than the manifest's `as_of` plus Restores (decisions N145, N157, review A-11).
//
// Document tags (decision N157, review A-13). A tag change creates no version, so the delta also carries a `documents`
// part: one line per document whose `(document_id, tag_generation)` differs between the two snapshots, with the
// document's current tags.
// After a delete expired the latest ready snapshot, the expunge starts a system-initiated snapshot (debounced 10 min
// per namespace), so read-only sync clients regain a servable copy.
//
// StreamSnapshot is SERVER-STREAMING: parts of ≤ 1 MiB, resumable by (path, offset). Unary "download a file" was
// rejected because gRPC messages should stay ≤ 4 MiB and files reach gigabytes.

