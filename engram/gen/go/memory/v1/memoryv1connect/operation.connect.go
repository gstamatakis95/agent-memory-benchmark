// Long-running operations. Every asynchronous unit of work is an Operation, and the workflow behind it depends on its
// kind (decision N136):
//   * RETAIN_DOCUMENT and CREATE_SNAPSHOT run as their own Temporal workflow,
//     id `ns/{namespace_id}/op/{operation_id}` on task queue `shard-{shard_id}` (decision D11);
//   * REFRESH_PAGE is singleton-backed: the refresh runs in the per-page
//     workflow `ns/{namespace_id}/page/{page_id}`, started or nudged by SignalWithStart with the operation_id in the
//     nudge; WaitOperation polls the page row, CancelOperation cancels nothing but the nudge, and a move's Restart
//     skips it (decision N157, review A-5);
//   * DELETE_DOCUMENT is the per-namespace Expunge singleton
//     (`ns/{namespace_id}/expunge`) plus the tombstone's `operation_id`, with progress read from the expunge's own
//     bookkeeping; DELETE_NAMESPACE runs the namespace Expunge at `ns/{namespace_id}/op/{operation_id}`; DELETE_TENANT
//     is derived from the catalog's tenant row;
//   * CONSOLIDATE is the per-namespace Consolidate singleton.
// OperationService is the read barrier of the consistency model (decision D16): after WaitOperation returns SUCCEEDED
// for a retain, Recall on the same namespace observes every fact of that document version unless `result.superseded_by`
// is set (decision N127).
//
// Deletes are different: a delete is effective when its RPC is acknowledged (committed marker plus durable intent
// object, decisions N115, N122); the Operation only tracks the asynchronous expunge (N119), so SUCCEEDED means
// "physically gone", not "hidden". A DELETE_* operation cannot be cancelled (FAILED_PRECONDITION +
// PreconditionFailed{OPERATION_NOT_CANCELLABLE}), and WaitOperation on it polls the tombstone (or the catalog row), not
// a workflow. A FAILED operation is never restarted under its id: a retry uses a new operation_id (decision N139). A
// namespace move is not an Operation: it lives on the catalog `namespace_moves` row and is visible only in
// memory.admin.v1 (N127).

