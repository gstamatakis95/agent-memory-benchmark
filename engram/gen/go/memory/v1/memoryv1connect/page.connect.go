// PageService (phase 3): mental models / knowledge pages — living markdown documents defined by a source query and a
// tag filter, refreshed after consolidation or on a schedule by an LLM delta-edit (decision D12). Staleness is tracked
// separately for writes (new evidence arrived) and deletes (cited evidence was removed), because a delete-stale page
// may be citing content that must not be shown, while a write-stale page is merely incomplete.
//
// Pages are versioned like observations: GetPage with as_of returns the version current at T (effective_at ≤ T <
// superseded_at, decision D9); NOT_FOUND when none exists. A page version is visible iff no fact input in its evidence
// segment is tombstoned or hidden and no observation-version input in its segment is hidden (decision N117); depth is
// fixed at two (fact, observation, page) and pages never feed observations. A page whose CURRENT version is hidden
// answers GetPage with FAILED_PRECONDITION + PreconditionFailed{PAGE_HIDDEN} until the refresh that the expunge always
// schedules lands.
